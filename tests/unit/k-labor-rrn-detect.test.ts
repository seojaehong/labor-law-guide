// k-labor 주민번호 모양 거름(lib/common.mjs) — 숫자 경계와 생년월일(YYMMDD)로 거른다. 값은 모두 합성.
// 261120 적대 검토: 경계가 없어 14자리 접수번호·더 긴 숫자 줄 속 13자리·법령 판 번호(6자리-시행일)를 주민번호로 잡았다.
import { describe, expect, it } from 'vitest';
import { argsLookLikeRrn, looksLikeRrn, mask } from '../../tools/k-labor/lib/common.mjs';

describe('looksLikeRrn — 숫자 경계 · 생년월일', () => {
  it.each([
    ['하이픈', '번호 900101-1234568 끝'],
    ['붙여 씀', '번호9001011234568번'],
    ['하이픈 앞뒤 띄어 씀', '900101 - 2234567'],
    ['2000년대생 뒷자리 4', '050505-4000000'],
    ['월말·12월', '991231-1000000'],
  ])('주민번호 모양은 잡는다: %s', (_, s) => {
    expect(looksLikeRrn(s)).toBe(true);
  });

  it.each([
    ['14자리 접수번호(앞 13자리가 주민번호 모양)', '접수번호 90010112345678'],
    ['14자리 접수번호(뒤 13자리가 주민번호 모양)', '접수번호 19001011234568'],
    ['더 긴 숫자 줄 속 13자리', '8890010112345681234'],
    ['월 13', '번호 901301-1234568 끝'],
    ['월 00', '번호 900001-1234568 끝'],
    ['일 32', '번호 900132-1234568 끝'],
    ['일 00', '번호 900100-1234568 끝'],
    ['법령 판 번호(6자리-시행일 8자리)', '000130-20261127'],
  ])('주민번호가 아니면 잡지 않는다: %s', (_, s) => {
    expect(looksLikeRrn(s)).toBe(false);
  });

  it('입력 전체(JSON) 검사도 같은 기준이다', () => {
    expect(argsLookLikeRrn({ receipt: '90010112345678' })).toBe(false);
    expect(argsLookLikeRrn({ amount: 90010112345678 })).toBe(false);
    expect(argsLookLikeRrn({ note: '900101-1234568' })).toBe(true);
  });

  it('응답 가림(mask)은 넓게 둔다 — 생년월일이 맞지 않아도 6-7 모양이면 가린다', () => {
    expect(mask('번호 901301-1234568')).toBe('번호 ******-*******');
  });
});
