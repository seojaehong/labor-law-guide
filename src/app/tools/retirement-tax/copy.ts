// 연금소득세를 뗀다(소득세법 §129①5의3). 「연금 외로 찾을 때 냅니다」만 쓰면 연금으로 받으면 세금이 없다는 뜻으로 읽힌다.
import type { RetirementTaxResult } from '@/lib/calc/retirement-tax';

const won = (n: number) => `${n.toLocaleString('ko-KR')}원`;

export function headline(r: RetirementTaxResult): string[] {
  if (r.incomeTax === 0) {
    // 퇴직급여 = 근속연수공제이면 §48② 상한은 걸리지 않지만(「미달」이 아니다) 공제가 퇴직급여를 다 덮는다 — 환산급여 0원을 이유로 댄다
    const why = r.serviceDeductionCapped
      ? `퇴직급여가 근속연수공제(${won(r.serviceDeductionTable)})보다 적어 공제하고 남는 금액이 없습니다.`
      : r.converted === 0
        ? `퇴직급여에서 근속연수공제(${won(r.serviceDeduction)})를 빼면 환산급여가 0원입니다.`
        : r.taxBase === 0
          ? '환산급여가 800만원 이하라 환산급여공제를 빼면 과세표준이 0원입니다.'
          : '산출세액이 10원이 되지 않아 10원 미만을 버리면 0원입니다.';
    return ['예상 퇴직소득세는 0원입니다.', why];
  }
  return [
    `예상 퇴직소득세는 ${won(r.incomeTax)}, 지방소득세는 ${won(r.localTax)}입니다.`,
    '연금계좌(개인형퇴직연금 IRP 등)로 받으면 지급할 때는 떼지 않고 나중에 찾을 때 냅니다. 연금으로 받으면 세율이 연금 외로 찾을 때의 70~50%로 줄어듭니다(소득세법 제146조 제2항, 제129조 제1항 제5호의3).',
  ];
}

