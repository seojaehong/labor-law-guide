export interface PlainRule {
  id: string;
  from: string;
  to: string;
  /** 화면에 보일 「무엇을 무엇으로」 */
  label: string;
  /** 뜻에 따라 바꿀지가 갈리는 말 — 자리만 알리고 고친 문안은 내지 않는다(일괄 반영에서 빠진다). 담당자가 조문별로 판단한다 */
  check?: string;
}

